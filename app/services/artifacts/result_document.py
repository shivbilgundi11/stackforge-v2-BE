"""The whole result as one Markdown document.

This is what "export this result" means when the user has not picked a single
artifact: everything the result page shows, in the order it shows it, in one
file. Metrics, tables, warnings, the artifacts the tool emitted, and the
provenance block.

The warnings are included, and that is a decision worth stating. It would look
better without them — a clean document with no caveats reads more confident.
It would also be the document someone forwards, which makes it the last place
a critical warning should be dropped: a stack export that omits "this component
is deprecated" is how a buried tool ends up in production.
"""

from __future__ import annotations

from app.services.artifacts import markdown as md
from app.services.artifacts.sources import RunSource, Source, StackSource

LEVEL_LABELS = {"critical": "Critical", "warning": "Warning", "info": "Note"}


def title_of(source: Source) -> tuple[str, str]:
    """`(title, subtitle)` — the cover of the PDF and the H1 of the Markdown."""
    if isinstance(source, StackSource):
        return source.title, f"Stack plan · version {source.version}"
    return source.title, f"{source.workflow.capitalize()} result · {source.tool_slug}"


def render(source: Source) -> str:
    if isinstance(source, StackSource):
        from app.services.artifacts import architecture

        return architecture.document(source).content
    return _run_document(source)


def _run_document(source: RunSource) -> str:
    output = source.output
    title, subtitle = title_of(source)

    sections = [
        f"# {title}\n",
        f"{subtitle} · run `{source.id}` · "
        f"{output.created_at.strftime('%Y-%m-%d %H:%M UTC')} · {output.source}\n",
    ]

    if inputs := md.key_values(source.input, key_header="Input"):
        sections.append(f"## Inputs\n\n{inputs}\n")

    figures = {
        key: value
        for key, value in output.metrics.items()
        if key not in {"summary", "rationale", "confidence"}
    }
    prose = [
        str(output.metrics[key])
        for key in ("summary", "rationale", "confidence")
        if output.metrics.get(key)
    ]
    if prose:
        sections.append("## Summary\n\n" + "\n\n".join(prose) + "\n")
    if figures_table := md.key_values(figures, key_header="Metric"):
        sections.append(f"## Figures\n\n{figures_table}\n")

    for name, rows in output.tables.items():
        rendered = md.table(rows)
        if rendered:
            sections.append(f"## {md.humanise(name)}\n\n{rendered}\n")

    if warnings := _warnings(source):
        sections.append(warnings)
    if artifacts := _artifacts(source):
        sections.append(artifacts)

    sections.append(_provenance(source))
    return "\n".join(sections)


def _warnings(source: RunSource) -> str:
    warnings = source.output.warnings
    if not warnings:
        return ""
    lines = "\n".join(
        f"- **{LEVEL_LABELS.get(warning.level, 'Note')}** — {warning.message}"
        for warning in sorted(
            warnings,
            # Critical first. A list that opens with three informational notes
            # is a list whose fourth entry does not get read.
            key=lambda item: {"critical": 0, "warning": 1, "info": 2}.get(item.level, 3),
        )
    )
    return f"## Warnings\n\n{lines}\n"


def _artifacts(source: RunSource) -> str:
    if not source.artifacts:
        return ""
    blocks = [
        f"### `{artifact.filename}`\n\n"
        + md.fence(artifact.content, language=artifact.language or artifact.format)
        for artifact in source.artifacts
    ]
    return "## Generated files\n\n" + "\n\n".join(blocks) + "\n"


def _provenance(source: RunSource) -> str:
    provenance = source.output.provenance
    if not provenance.sources:
        return (
            "---\n\nGenerated by StackForge. No priced catalog rows were read for "
            "this run, so there is nothing to attribute.\n"
        )

    lines = "\n".join(
        f"- **{entry.name}** — verified {entry.last_verified_at.strftime('%Y-%m-%d')} "
        f"({entry.age_days} days ago, {entry.variant}) · {entry.url}"
        for entry in provenance.sources
    )
    oldest = (
        provenance.oldest_verified_at.strftime("%Y-%m-%d")
        if provenance.oldest_verified_at
        else "unknown"
    )
    return f"""---

## Sources

The oldest row behind these figures was verified {oldest}. That is the date this
result should be judged on — a result is only as fresh as its worst input.

{lines}

Prices are hand-verified against each provider's published page. There are no
pricing APIs and no scraping anywhere in this product.
"""

ARCHETYPES: Final = {
    "ollama-webui": ("Ollama + Open WebUI", _ollama_stack),
    "vllm-redis": ("vLLM + Redis", _vllm_stack),
    "fastapi-pgvector": ("FastAPI + pgvector + Redis", _pgvector_stack),
    "rag-stack": ("vLLM + Qdrant + Redis", _rag_stack),
}


def docker_compose(
    *, archetype: str, model: str, gpu: bool = True
) -> tuple[list[Artifact], list[ToolWarning]]:
    label, builder = ARCHETYPES.get(archetype, ARCHETYPES["ollama-webui"])
    services, env = builder(model, gpu=gpu)

    # Named volumes are declared from what the services actually mount, so a
    # service added above cannot produce a file that fails on an undeclared
    # volume.
    volumes: dict[str, None] = {}
    for service in services.values():
        for mount in service.get("volumes", []):
            name = str(mount).split(":", 1)[0]
            if not name.startswith((".", "/")):
                volumes[name] = None

    document: dict[str, Any] = {"services": services}
    if volumes:
        document["volumes"] = volumes

    warnings: list[ToolWarning] = [
        ToolWarning(
            level="info",
            message=(
                f"{label} is a starter template. Secrets come from .env, volumes are "
                "local, and the health checks assume a model that loads inside 60 "
                "seconds — check that against yours before relying on it."
            ),
        )
    ]
    if gpu:
        warnings.append(
            ToolWarning(
                level="info",
                message=(
                    "GPU reservations need the NVIDIA Container Toolkit on the host. "
                    "Without it the container starts and silently runs on CPU."
                ),
            )
        )

    return [
        Artifact(
            type="compose",
            format="yaml",
            filename="docker-compose.yml",
            content=STARTER_HEADER + "\n" + _dump(document),
            language="yaml",
        ),
        Artifact(
            type="env",
            format="text",
            filename=".env.example",
            content="\n".join(f"{key}={value}" for key, value in env.items()) + "\n",
        ),
    ], warnings



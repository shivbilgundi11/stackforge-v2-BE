"""Generated deployment files (WF4).

Everything here is emitted through `yaml.safe_dump` from a Python structure,
never by string interpolation into a template. A model name with a colon in
it - which every Ollama tag has - turns a hand-built YAML line into a
different key, and the file parses successfully as the wrong thing. That
failure surfaces at deploy time, in someone else's terminal.

Every file carries a header saying it is a starter template and naming what
still needs review. The previous build presented generated infrastructure as
production-ready, which is both untrue and more expensive to support than the
sentence that says otherwise.
"""

from __future__ import annotations

from typing import Any, Final

import yaml

from app.schemas.tools import Artifact, ToolWarning

STARTER_HEADER: Final = """# Generated by StackForge.
# STARTER TEMPLATE - not a production deployment.
#
# Review before running:
#   - secrets are read from .env; nothing here is a credential
#   - volumes are named and local; point them at real storage
#   - health checks are conservative; tune to your model's load time
#   - resource limits are a starting point, not a measurement
"""


def _dump(document: dict[str, Any]) -> str:
    """Deterministic YAML, keys in insertion order rather than sorted.

    `sort_keys=False` because a Compose file reading `image`, `ports`,
    `environment` is a file someone can scan; alphabetical order puts
    `deploy` above `image` and makes it a lookup exercise.
    """
    dumped: str = yaml.safe_dump(document, sort_keys=False, default_flow_style=False, width=100)
    return dumped



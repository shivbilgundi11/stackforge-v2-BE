GPU_RESERVATION: Final = {
    "resources": {
        "reservations": {"devices": [{"driver": "nvidia", "count": "all", "capabilities": ["gpu"]}]}
    }
}


def _service(
    image: str,
    *,
    ports: list[str] | None = None,
    environment: dict[str, str] | None = None,
    volumes: list[str] | None = None,
    gpu: bool = False,
    healthcheck: list[str] | None = None,
    depends_on: list[str] | None = None,
    command: str | None = None,
) -> dict[str, Any]:
    service: dict[str, Any] = {"image": image, "restart": "unless-stopped"}
    if command:
        service["command"] = command
    if ports:
        service["ports"] = ports
    if environment:
        service["environment"] = environment
    if volumes:
        service["volumes"] = volumes
    if depends_on:
        # `service_healthy` rather than a bare list: a dependency that has
        # started is not a dependency that is ready, and a vector store that
        # is still opening its index will refuse the first writes.
        service["depends_on"] = {name: {"condition": "service_healthy"} for name in depends_on}
    if healthcheck:
        service["healthcheck"] = {
            "test": healthcheck,
            "interval": "30s",
            "timeout": "10s",
            "retries": 5,
            "start_period": "60s",
        }
    if gpu:
        service["deploy"] = GPU_RESERVATION
    return service


def _ollama_stack(model: str, *, gpu: bool) -> tuple[dict[str, Any], dict[str, str]]:
    services = {
        "ollama": _service(
            "ollama/ollama:latest",
            ports=["11434:11434"],
            volumes=["ollama-models:/root/.ollama"],
            gpu=gpu,
            healthcheck=["CMD", "ollama", "list"],
        ),
        "open-webui": _service(
            "ghcr.io/open-webui/open-webui:main",
            ports=["3000:8080"],
            environment={
                "OLLAMA_BASE_URL": "http://ollama:11434",
                "WEBUI_SECRET_KEY": "${WEBUI_SECRET_KEY}",
            },
            volumes=["open-webui:/app/backend/data"],
            depends_on=["ollama"],
        ),
    }
    env = {"WEBUI_SECRET_KEY": "change-me", "OLLAMA_MODEL": model}
    return services, env



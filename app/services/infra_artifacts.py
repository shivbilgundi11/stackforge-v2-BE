def k8s_manifests(
    *,
    name: str,
    image: str,
    replicas: int,
    cpu_request: str,
    cpu_limit: str,
    memory_request_gi: int,
    memory_limit_gi: int,
    gpu_count: int,
    target_utilisation: int,
    max_replicas: int,
) -> tuple[list[Artifact], list[ToolWarning]]:
    labels = {"app": name}

    container: dict[str, Any] = {
        "name": name,
        "image": image,
        "ports": [{"containerPort": 8000, "name": "http"}],
        "resources": {
            "requests": {
                "cpu": cpu_request,
                "memory": f"{memory_request_gi}Gi",
            },
            "limits": {
                "cpu": cpu_limit,
                "memory": f"{memory_limit_gi}Gi",
            },
        },
        # A model server takes minutes to load weights. A readiness probe with
        # the default timings marks it unhealthy and restarts it forever, which
        # looks like a crash loop and is actually an impatient probe.
        "readinessProbe": {
            "httpGet": {"path": "/health", "port": "http"},
            "initialDelaySeconds": 60,
            "periodSeconds": 10,
            "failureThreshold": 30,
        },
        "livenessProbe": {
            "httpGet": {"path": "/health", "port": "http"},
            "initialDelaySeconds": 300,
            "periodSeconds": 30,
        },
    }
    if gpu_count:
        container["resources"]["requests"]["nvidia.com/gpu"] = gpu_count
        container["resources"]["limits"]["nvidia.com/gpu"] = gpu_count

    deployment = {
        "apiVersion": "apps/v1",
        "kind": "Deployment",
        "metadata": {"name": name, "labels": labels},
        "spec": {
            "replicas": replicas,
            "selector": {"matchLabels": labels},
            "template": {
                "metadata": {"labels": labels},
                "spec": {"containers": [container]},
            },
        },
    }

    service = {
        "apiVersion": "v1",
        "kind": "Service",
        "metadata": {"name": name, "labels": labels},
        "spec": {
            "selector": labels,
            "ports": [{"port": 80, "targetPort": "http", "name": "http"}],
            "type": "ClusterIP",
        },
    }

    hpa = {
        "apiVersion": "autoscaling/v2",
        "kind": "HorizontalPodAutoscaler",
        "metadata": {"name": name},
        "spec": {
            "scaleTargetRef": {"apiVersion": "apps/v1", "kind": "Deployment", "name": name},
            "minReplicas": replicas,
            "maxReplicas": max_replicas,
            "metrics": [
                {
                    "type": "Resource",
                    "resource": {
                        "name": "cpu",
                        "target": {"type": "Utilization", "averageUtilization": target_utilisation},
                    },
                }
            ],
        },
    }

    pdb = {
        "apiVersion": "policy/v1",
        "kind": "PodDisruptionBudget",
        "metadata": {"name": name},
        # maxUnavailable rather than minAvailable: at one replica, a
        # minAvailable of 1 blocks every voluntary eviction and node drains
        # hang until someone deletes the budget.
        "spec": {"maxUnavailable": 1, "selector": {"matchLabels": labels}},
    }

    warnings: list[ToolWarning] = [
        ToolWarning(
            level="info",
            message=(
                "Starter manifests. Requests and limits are derived from the VRAM "
                "estimate and a standard headroom factor, not from a measurement of "
                "your workload — load test before trusting them."
            ),
        )
    ]
    if gpu_count:
        warnings.append(
            ToolWarning(
                level="warning",
                message=(
                    "The HPA scales on CPU because GPU utilisation is not a core "
                    "metric. On a GPU deployment CPU stays flat while the accelerator "
                    "saturates, so this will not scale when you need it to. Use KEDA "
                    "on queue depth, or the DCGM exporter with custom metrics."
                ),
            )
        )

    return [
        Artifact(
            type="k8s-deployment",
            format="yaml",
            filename="deployment.yaml",
            content=STARTER_HEADER + "\n" + _dump(deployment),
            language="yaml",
        ),
        Artifact(
            type="k8s-service",
            format="yaml",
            filename="service.yaml",
            content=_dump(service),
            language="yaml",
        ),
        Artifact(
            type="k8s-hpa",
            format="yaml",
            filename="hpa.yaml",
            content=_dump(hpa),
            language="yaml",
        ),
        Artifact(
            type="k8s-pdb",
            format="yaml",
            filename="pdb.yaml",
            content=_dump(pdb),
            language="yaml",
        ),
    ], warnings

"""The tool catalog, including the Tool Graveyard.

`status` and `status_reason` together are the Graveyard. Everything marked
`deprecated` or `not_for_production` shows up there with its reason and its
suggested alternatives, and every stack containing one gets a warning. Because
status is a column, an editor changes it and the site changes on the next
request — no deploy, which is the whole point.

`facts` carries the raw values the comparison engine scores against. Keeping
them in JSONB means adding a comparison criterion is a data change rather than
a migration. Cost is deliberately *not* in here: cost is computed from the
user's stated scale at request time, because a stored "cost: 7/10" is wrong the
day a provider changes price.
"""


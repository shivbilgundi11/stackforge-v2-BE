"""Model pricing seed.

Prices are stated **per 1M tokens**, the unit every provider publishes in. The
loader divides by 1000 once, so the database stores per-1k and no consumer
repeats the conversion.

`verified` is the date the row was actually checked against its source, not the
date the file was written. The three big providers were read from their live
pricing pages on 2026-08-09; the Anthropic table came from the vendor's own
published rate card dated 2026-06-24; the long tail was carried forward from
the previous build's seed at its original 2026-06-29 date and is deliberately
*not* backdated to today. The provenance chip is worthless if the dates are
decorative — a row that has not been re-read should look old, because it is.
"""

from __future__ import annotations

from datetime import date
from typing import NamedTuple

VERIFIED_LIVE = date(2026, 8, 9)
VERIFIED_ANTHROPIC = date(2026, 6, 24)
VERIFIED_CARRIED = date(2026, 6, 29)



    provider: str
    model_id: str
    display_name: str
    family: str
    input_per_m: str
    output_per_m: str | None
    cached_input_per_m: str | None
    context_window: int | None
    max_output_tokens: int | None
    dimensions: int | None
    capabilities: dict[str, bool]
    tokenizer: str | None
    source: str
    verified: date
    status: str = "active"
    status_reason: str | None = None


